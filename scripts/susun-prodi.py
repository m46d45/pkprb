    known = known_names()
    iabee = load_old_iabee()
    groups: dict[str, Counter[str]] = defaultdict(Counter)
    for row in rows:
        groups[fold(row["Institusi"])][row["Institusi"]] += 1
    canonical = {key: choose_name(spellings, known) for key, spellings in groups.items()}

    coords = json.loads(COORDS.read_text())
