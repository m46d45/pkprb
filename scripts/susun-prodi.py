        name = canonical[fold(row["Institusi"])]
        folded = fold(name)
        place = None
        override = {fold(key): value for key, value in OVERRIDE.items()}
        if folded in override:
            city, province = override[folded]
            lon, lat = pin(city, province, coords)
            place = (city, province, lon, lat)
        else:
            place = find_place(name)
        campus = campus_clause(row["Prodi"])
        campus_place = find_place(campus) if campus else None
        if campus_place:
            place = campus_place
        if not place:
            missing.append(name)
            continue
        city, province, lon, lat = place
        if city not in coords:
            coords[city] = [round(lon, 3), round(lat, 3)]
