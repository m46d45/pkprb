def fold(value: str) -> str:
    text = value.casefold().replace("`", "").replace("’", "'")
    text = text.replace("aa", "a") if False else text
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def strata_of(value: str) -> str:
    key = fold(value)
    if key not in STRATA:
        raise SystemExit(f"jenjang tidak dikenal: {value}")
    return STRATA[key]


PLACES_SORTED = sorted(PLACES, key=lambda item: len(item[0]), reverse=True)


def find_place(text: str) -> tuple[str, str, float, float] | None:
    folded = fold(text)
    for needle, city, province, lon, lat in PLACES_SORTED:
        if re.search(rf"(^| ){re.escape(needle)}( |$)", folded):
            return city, province, lon, lat
    return None


def campus_clause(program: str) -> str:
    match = re.search(r"kampus\s+(.+)$", program, re.I)
    return match.group(1) if match else ""


def load_old_iabee() -> dict[tuple[str, str, str], str]:
    text = PROGRAMS_TS.read_text()
    found: dict[tuple[str, str, str], str] = {}
    for block in re.findall(r"\{[^{}]+\}", text):
        if '"iabee"' not in block:
            continue
        uni = re.search(r'"university": "([^"]+)"', block)
        prog = re.search(r'"program": "([^"]+)"', block)
        strata = re.search(r'"strata": "([^"]+)"', block)
        iabee = re.search(r'"iabee": "([^"]+)"', block)
        if not (uni and prog and strata and iabee):
            continue
        if iabee.group(1) == "none":
            continue
        found[(fold(uni.group(1)), fold(prog.group(1)), strata.group(1))] = iabee.group(1)
    return found


