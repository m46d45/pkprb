def pin(city: str, province: str, coords: dict) -> tuple[float, float]:
    if city in coords:
        lon, lat = coords[city]
        return float(lon), float(lat)
    for _needle, place_city, _province, lon, lat in PLACES:
        if place_city == city:
            return lon, lat
    found = find_place(city)
    if found and found[0] == city:
        return found[2], found[3]
    lon, lat = CAPITAL[province]
    return lon, lat


def choose_name(spellings: Counter[str], known: set[str]) -> str:
    for name in spellings:
        if name in known:
            return name
    return spellings.most_common(1)[0][0]


